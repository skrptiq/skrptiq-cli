#!/usr/bin/env node
/**
 * regen-protocol.mjs — GH#866 / K-055.
 *
 * Mechanically derive the frozen protocol-v2 CONSTANTS from the skrptiq-extension
 * SoT (shared/protocol.ts) into a checked-in golden, so the Go bridge's
 * conformance test guards against drift without hand-copying. The runtime numeric
 * constants are imported (authoritative); the BridgeErrorCode union is extracted
 * textually (it is a TS type, erased at runtime) — both mechanical, neither typed
 * by hand into Go.
 *
 * Output: internal/bridge/protocol.golden.json
 *
 * Usage: node scripts/regen-protocol.mjs [path-to-skrptiq-extension]
 */

import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const extDir = resolve(
  process.argv[2] || process.env.SKRPTIQ_EXTENSION_DIR || "../skrptiq-extension",
);
const protoTs = join(extDir, "shared", "protocol.ts");
const outDir = resolve(new URL("../internal/bridge", import.meta.url).pathname);

function fail(msg) {
  console.error(`[regen-protocol] ${msg}`);
  process.exit(1);
}

let esbuild;
try {
  const req = createRequire(join(extDir, "package.json"));
  esbuild = await import(pathToFileURL(req.resolve("esbuild")).href);
} catch (err) {
  fail(`could not load esbuild from ${extDir}/node_modules (${err?.message ?? err})`);
}

let source;
try {
  source = readFileSync(protoTs, "utf8");
} catch {
  fail(`protocol SoT not found at ${protoTs}`);
}

// Import the runtime constants (authoritative numeric values).
const tmp = mkdtempSync(join(tmpdir(), "skrptiq-proto-"));
const bundle = join(tmp, "protocol.mjs");
await esbuild.build({
  entryPoints: [protoTs],
  bundle: true,
  format: "esm",
  platform: "neutral",
  outfile: bundle,
  logLevel: "silent",
});
const mod = await import(pathToFileURL(bundle).href);

// Extract the BridgeErrorCode union members textually (a TS type — no runtime value).
// Strip line comments first: a `;` inside a trailing `// …` comment would otherwise
// truncate the non-greedy match mid-union.
const noComments = source.replace(/\/\/[^\n]*/g, "");
const unionMatch = noComments.match(/export type BridgeErrorCode =([\s\S]*?);/);
if (!unionMatch) fail("could not locate the BridgeErrorCode union in protocol.ts");
const errorCodes = [...unionMatch[1].matchAll(/'([a-z_]+)'/g)].map((m) => m[1]);
if (errorCodes.length === 0) fail("extracted 0 error codes — union shape changed?");

const golden = {
  note: "Generated by scripts/regen-protocol.mjs from skrptiq-extension shared/protocol.ts — do not edit by hand.",
  sourceCommit: null, // filled below (best-effort)
  sourceSha256: createHash("sha256").update(source).digest("hex"),
  protocolVersion: mod.PROTOCOL_VERSION,
  defaultInvokeTimeoutMs: mod.DEFAULT_INVOKE_TIMEOUT_MS,
  nmHostToExtMaxBytes: mod.NM_HOST_TO_EXT_MAX_BYTES,
  nmExtToHostMaxBytes: mod.NM_EXT_TO_HOST_MAX_BYTES,
  errorCodes,
};
try {
  const { execFileSync } = await import("node:child_process");
  golden.sourceCommit = execFileSync("git", ["-C", extDir, "rev-parse", "HEAD"], {
    encoding: "utf8",
  }).trim();
} catch {
  /* best-effort */
}

writeFileSync(join(outDir, "protocol.golden.json"), JSON.stringify(golden, null, 2) + "\n");
console.error(
  `[regen-protocol] v${golden.protocolVersion}, ${errorCodes.length} error codes, timeout ${golden.defaultInvokeTimeoutMs}ms`,
);
